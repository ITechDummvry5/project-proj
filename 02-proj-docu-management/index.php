<?php
// Function to get the total hours of support from the 'sessions' table
function getTotalSupportHours() {
    global $conn;
    $query = "SELECT login_time, logout_time FROM sessions";  // Query to fetch login and logout times
    $result = mysqli_query($conn, $query);
    
    $totalHours = 0;
    
    if ($result) {
        while ($row = mysqli_fetch_assoc($result)) {
            $loginTime = strtotime($row['login_time']);  // Convert login time to timestamp
            $logoutTime = strtotime($row['logout_time']);  // Convert logout time to timestamp
            
            if ($loginTime && $logoutTime) {
                // Calculate the difference in hours
                $hoursWorked = ($logoutTime - $loginTime) / 3600;  // Convert seconds to hours
                $totalHours += $hoursWorked;  // Add to the total hours
            }
        }
        return round($totalHours, 2);  // Return the total hours rounded to 2 decimal places
    }
    return 0; // Return 0 if the query fails or no result
}

// Call the function to get the total hours
$totalSupportHours = getTotalSupportHours();
?>

